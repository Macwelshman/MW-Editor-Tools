const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const ts=require('../UI/node_modules/typescript');
const exported={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname,'../UI/src/launcher-position.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:exported});
const rect=(left,top=65,width=56,height=56)=>({left,right:left+width,top,bottom:top+height,width,height});
const position=(neighbours,own=rect(520),base=520,gap=8)=>exported.launcherLeft(base,own,neighbours,gap);
assert.equal(position([]),520,'Empty row uses its top-left slot');
assert.equal(position([rect(520)]),584,'Occupied slot shifts right with a gap');
assert.equal(position([rect(584),rect(520)]),648,'Multiple icons are handled in either DOM order');
assert.equal(position([rect(648)]),520,'A free first slot is retained');
assert.equal(position([rect(520,130)]),520,'Other rows do not displace the icon');
assert.equal(position([rect(520,0)]),520,'Buttons above the row do not displace the icon');
assert.equal(position([rect(510,65,80)]),598,'Partial overlaps and wider icons are cleared');
assert.equal(position([rect(520,65,0,0)]),520,'Unmeasured or hidden buttons do not occupy a slot');
assert.equal(position([rect(520)],rect(648)),584,'Rechecking starts at the original anchor instead of drifting right');
assert.equal(position([],rect(648)),520,'Removing neighbours reclaims the first slot');
assert.equal(position([rect(1040,130,112,112)],rect(1040,130,112,112),1040,16),1168,'Scaled interface keeps scaled spacing');
assert.equal(position([rect(300,65,200)]),520,'Sidebar controls left of the anchor leave the slot clear');
console.log('PASS: 12 launcher placement checks.');
